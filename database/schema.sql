-- =============================================================================
-- COOPERATIVA AGROPECUARIA POLLOLANDIA R.L. — Sistema Contable (prueba piloto)
-- schema.sql — Esquema relacional para SQLite 3.35+ (migrable a PostgreSQL 14+)
--
-- Fuentes de diseño:
--   * Plan de Cuentas Contable (4 niveles, Grupos 1-9) y hoja "Sufijos de Costos"
--   * MOF Área Financiera y Contable (MOF-FIN-001 v1.0): roles, autoridad y SoD
--   * Manual del Sistema de Costos (MAN-01): centros de costo, sufijos, lotes de 73 días
--   * Anexo 3 Organigrama
--
-- Orden: 1 Seguridad · 2 Ejercicio · 3 Plan de cuentas · 4 Centros de costo y
--        sufijos · 5 Libro diario · 6 Lotes · 7 Detalle de asientos · 8 Auditoría
--        · 9 Vistas · 10 Triggers (específicos de SQLite)
--
-- Convenciones y guía de migración a PostgreSQL:
--   * PK:        INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT GENERATED BY DEFAULT AS IDENTITY
--   * Banderas:  INTEGER 0/1 con CHECK               -> BOOLEAN (quitar el CHECK)
--   * Dinero:    NUMERIC(14,2) en Bolivianos (BOB). SQLite lo guarda con afinidad numérica;
--                el ORM debe usar Decimal y las comparaciones de cuadre usan ROUND(.,2).
--   * Fechas:    DATE / TIMESTAMP (SQLite las guarda como texto ISO-8601, en UTC).
--   * Triggers:  la sección 10 usa sintaxis SQLite (RAISE, julianday, substr). En PostgreSQL
--                reescribir como funciones PL/pgSQL + CREATE TRIGGER ... EXECUTE FUNCTION.
--   * Integridad referencial: cada conexión SQLite debe ejecutar PRAGMA foreign_keys = ON
--                (app/core/database.py ya lo hace).
-- =============================================================================

PRAGMA foreign_keys = ON;

-- =============================================================================
-- 1. SEGURIDAD: ROLES (MOF) Y USUARIOS
--    Roles = cargos y órganos del MOF con atribuciones sobre el área financiera.
--    La segregación de funciones (MOF 3.2) se materializa en roles_permisos:
--    quien autoriza (GG) no registra; quien registra (JF) no autoriza;
--    quien verifica (CV) no ejecuta.
-- =============================================================================

CREATE TABLE roles (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo          TEXT    NOT NULL UNIQUE CHECK (codigo = upper(codigo)),   -- GG, JF, CA, CV, UT
    nombre          TEXT    NOT NULL,
    descripcion     TEXT,
    referencia_mof  TEXT,                                                      -- sección del MOF
    activo          INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0, 1))
);

CREATE TABLE permisos (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo       TEXT NOT NULL UNIQUE,            -- p. ej. 'asientos.registrar'
    modulo       TEXT NOT NULL,
    descripcion  TEXT NOT NULL
);

CREATE TABLE roles_permisos (
    rol_id      INTEGER NOT NULL REFERENCES roles(id)    ON DELETE CASCADE,
    permiso_id  INTEGER NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE usuarios (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    username         TEXT    NOT NULL UNIQUE,
    nombre_completo  TEXT    NOT NULL,
    email            TEXT    UNIQUE,
    password_hash    TEXT    NOT NULL,            -- nunca texto plano (ver app/core/security.py)
    rol_id           INTEGER NOT NULL REFERENCES roles(id),   -- un rol por usuario (evita incompatibilidades SoD)
    es_socio         INTEGER NOT NULL DEFAULT 1 CHECK (es_socio IN (0, 1)),
    activo           INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    ultimo_acceso    TIMESTAMP,
    creado_en        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_usuarios_rol ON usuarios(rol_id);

-- =============================================================================
-- 2. EJERCICIO FISCAL (cierre al 30 de junio — cuenta 8.1.01.01 y MOF 1.1)
-- =============================================================================

CREATE TABLE ejercicios_fiscales (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo        TEXT NOT NULL UNIQUE,                          -- '2026-2027'
    fecha_inicio  DATE NOT NULL,
    fecha_fin     DATE NOT NULL,
    estado        TEXT NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO', 'CERRADO')),
    cerrado_en    TIMESTAMP,
    CHECK (fecha_fin > fecha_inicio),
    CHECK (estado = 'ABIERTO' OR cerrado_en IS NOT NULL)
);

-- =============================================================================
-- 3. PLAN DE CUENTAS — 4 NIVELES
--    Nivel 1 Grupo (1) · Nivel 2 Clasificación (1.1) · Nivel 3 Subgrupo (1.1.01)
--    Nivel 4 Cuenta (1.1.01.01). Solo el nivel 4 es imputable (recibe movimientos).
-- =============================================================================

CREATE TABLE cuentas (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo           TEXT    NOT NULL UNIQUE,
    nombre           TEXT    NOT NULL,
    nivel            INTEGER NOT NULL CHECK (nivel BETWEEN 1 AND 4),
    cuenta_padre_id  INTEGER REFERENCES cuentas(id),
    grupo            INTEGER NOT NULL CHECK (grupo BETWEEN 1 AND 9),
    naturaleza       TEXT    NOT NULL CHECK (naturaleza IN ('DEUDORA', 'ACREEDORA', 'DUAL')),
    es_imputable     INTEGER NOT NULL DEFAULT 0 CHECK (es_imputable IN (0, 1)),
    es_centro_costo  INTEGER NOT NULL DEFAULT 0 CHECK (es_centro_costo IN (0, 1)),  -- 6.1.01.01 / 6.1.01.02
    descripcion      TEXT,
    vigente_desde    DATE,                                      -- cuentas marcadas (*) en el plan: 2027
    activa           INTEGER NOT NULL DEFAULT 1 CHECK (activa IN (0, 1)),
    creado_en        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- longitud del código por nivel: '1' | '1.1' | '1.1.01' | '1.1.01.01'
    CHECK (length(codigo) = CASE nivel WHEN 1 THEN 1 WHEN 2 THEN 3 WHEN 3 THEN 6 ELSE 9 END),
    CHECK ((nivel = 1 AND cuenta_padre_id IS NULL) OR (nivel > 1 AND cuenta_padre_id IS NOT NULL)),
    CHECK ((nivel = 4 AND es_imputable = 1) OR (nivel < 4 AND es_imputable = 0)),
    CHECK (es_centro_costo = 0 OR nivel = 4),
    CHECK (grupo = CAST(substr(codigo, 1, 1) AS INTEGER))
);
CREATE INDEX idx_cuentas_padre ON cuentas(cuenta_padre_id);
CREATE INDEX idx_cuentas_grupo ON cuentas(grupo, nivel);

-- =============================================================================
-- 4. GRUPO 6 — SISTEMA MATRICIAL DE COSTOS (MAN-01)
--    Centro de costo (CC-01 Carne, CC-02 Alimento) x Sufijo (-01 a -41) x Lote.
--    El centro de costo es una cuenta puente: acumula durante el ciclo y queda
--    en saldo cero al cierre (se transfiere a 1.1.03.12 / 1.1.03.13).
-- =============================================================================

CREATE TABLE centros_costo (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo         TEXT NOT NULL UNIQUE,                         -- 'CC-01', 'CC-02'
    nombre         TEXT NOT NULL,
    cuenta_id      INTEGER NOT NULL UNIQUE REFERENCES cuentas(id),   -- 6.1.01.01 / 6.1.01.02
    unidad_medida  TEXT NOT NULL CHECK (unidad_medida IN ('KG', 'QQ')),   -- costo unitario Bs/kg o Bs/QQ
    descripcion    TEXT,
    vigente_desde  DATE,
    activo         INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0, 1))
);

CREATE TABLE sufijos_costo (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo           TEXT NOT NULL UNIQUE CHECK (length(codigo) = 2),   -- '01'..'41' (se muestra 6.1.01.01-01)
    nombre           TEXT NOT NULL,
    elemento_costo   TEXT NOT NULL CHECK (elemento_costo IN ('MPD', 'MOD', 'CIF', 'PERDIDA_ORDINARIA')),
    naturaleza       TEXT NOT NULL DEFAULT 'DEUDORA' CHECK (naturaleza IN ('DEUDORA', 'ACREEDORA')),
    descripcion      TEXT,
    vigente_desde    DATE,
    activo           INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0, 1))
);

-- Matriz de aplicabilidad: qué sufijos puede recibir cada centro de costo.
CREATE TABLE centro_costo_sufijos (
    centro_costo_id  INTEGER NOT NULL REFERENCES centros_costo(id) ON DELETE CASCADE,
    sufijo_id        INTEGER NOT NULL REFERENCES sufijos_costo(id) ON DELETE CASCADE,
    PRIMARY KEY (centro_costo_id, sufijo_id)
);

-- =============================================================================
-- 5. LIBRO DIARIO — CABECERA DE ASIENTOS
--    Flujo: BORRADOR -> CONTABILIZADO -> ANULADO. Los asientos contabilizados son
--    inmutables; se corrigen con un asiento de ANULACION (contrapartida).
--    MOF 2.2(e): ajustes y cierres requieren autorización de la GG, y quien
--    autoriza no puede ser quien registra.
-- =============================================================================

CREATE TABLE asientos (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    ejercicio_id        INTEGER NOT NULL REFERENCES ejercicios_fiscales(id),
    numero              INTEGER NOT NULL CHECK (numero > 0),          -- correlativo por ejercicio
    fecha               DATE    NOT NULL,
    tipo                TEXT    NOT NULL CHECK (tipo IN
                            ('APERTURA', 'DIARIO', 'AJUSTE', 'CIERRE_CICLO', 'CIERRE_EJERCICIO', 'ANULACION')),
    glosa               TEXT    NOT NULL,
    documento_respaldo  TEXT,                                          -- p. ej. FIN-TRA-06, nota de entrega
    estado              TEXT    NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN ('BORRADOR', 'CONTABILIZADO', 'ANULADO')),
    asiento_origen_id   INTEGER REFERENCES asientos(id),               -- solo para ANULACION
    creado_por          INTEGER NOT NULL REFERENCES usuarios(id),
    creado_en           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    autorizado_por      INTEGER REFERENCES usuarios(id),
    autorizado_en       TIMESTAMP,
    contabilizado_en    TIMESTAMP,
    UNIQUE (ejercicio_id, numero),
    CHECK (autorizado_por IS NULL OR autorizado_por <> creado_por),    -- SoD: quien autoriza no registra
    CHECK (tipo NOT IN ('AJUSTE', 'CIERRE_CICLO', 'CIERRE_EJERCICIO', 'ANULACION')
           OR estado = 'BORRADOR' OR autorizado_por IS NOT NULL),
    CHECK ((tipo = 'ANULACION' AND asiento_origen_id IS NOT NULL)
           OR (tipo <> 'ANULACION' AND asiento_origen_id IS NULL)),
    CHECK (estado = 'BORRADOR' OR contabilizado_en IS NOT NULL)
);
CREATE INDEX idx_asientos_fecha  ON asientos(fecha);
CREATE INDEX idx_asientos_estado ON asientos(estado);

-- =============================================================================
-- 6. LOTES — CICLO PRODUCTIVO DE 73 DÍAS (PC-04)
--    Unidad básica de costeo: un lote = un ciclo abierto y cerrado en un centro
--    de costo. Los kg / QQ producidos y el costo unitario se fijan al cierre.
-- =============================================================================

CREATE TABLE lotes (
    id                   INTEGER PRIMARY KEY AUTOINCREMENT,
    codigo               TEXT    NOT NULL UNIQUE,                      -- p. ej. 'L-CC01-2026-2027-01'
    centro_costo_id      INTEGER NOT NULL REFERENCES centros_costo(id),
    ejercicio_id         INTEGER NOT NULL REFERENCES ejercicios_fiscales(id),
    numero_ciclo         INTEGER NOT NULL CHECK (numero_ciclo > 0),    -- hasta 5 ciclos por año
    fecha_inicio         DATE    NOT NULL,                             -- recepción de pollitos BB (día 1)
    duracion_dias        INTEGER NOT NULL DEFAULT 73 CHECK (duracion_dias = 73),
    fecha_fin_prevista   DATE    NOT NULL,                             -- día 73: faenado / cierre
    fecha_cierre         DATE,
    estado               TEXT    NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO', 'CERRADO', 'ANULADO')),
    -- Producción de carne (CC-01)
    aves_iniciales       INTEGER CHECK (aves_iniciales IS NULL OR aves_iniciales > 0),
    aves_faenadas        INTEGER CHECK (aves_faenadas IS NULL OR aves_faenadas >= 0),
    kg_producidos        NUMERIC(12,2) CHECK (kg_producidos IS NULL OR kg_producidos >= 0),
    -- Producción de alimento balanceado (CC-02)
    qq_producidos        NUMERIC(12,2) CHECK (qq_producidos IS NULL OR qq_producidos >= 0),
    qq_consumo_propio    NUMERIC(12,2) CHECK (qq_consumo_propio IS NULL OR qq_consumo_propio >= 0),
    qq_excedente         NUMERIC(12,2) CHECK (qq_excedente IS NULL OR qq_excedente >= 0),
    -- Resultado del cierre (Informe de Costo de Ciclo, FIN-TRA-06)
    costo_total          NUMERIC(14,2) CHECK (costo_total IS NULL OR costo_total >= 0),
    costo_unitario       NUMERIC(12,4) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),   -- Bs/kg o Bs/QQ
    asiento_cierre_id    INTEGER REFERENCES asientos(id),
    responsable_id       INTEGER REFERENCES usuarios(id),              -- encargado de granja (UT)
    observaciones        TEXT,
    creado_en            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (centro_costo_id, ejercicio_id, numero_ciclo),
    CHECK (fecha_fin_prevista >= fecha_inicio),
    CHECK (aves_faenadas IS NULL OR aves_iniciales IS NULL OR aves_faenadas <= aves_iniciales),
    CHECK (estado <> 'CERRADO'
           OR (fecha_cierre IS NOT NULL AND costo_total IS NOT NULL AND asiento_cierre_id IS NOT NULL))
);
CREATE INDEX idx_lotes_estado ON lotes(estado);

-- Bitácora diaria (la provee la Unidad Técnica; no registra contabilidad).
CREATE TABLE lote_bitacora (
    id                 INTEGER PRIMARY KEY AUTOINCREMENT,
    lote_id            INTEGER NOT NULL REFERENCES lotes(id),
    fecha              DATE    NOT NULL,
    dia_ciclo          INTEGER NOT NULL CHECK (dia_ciclo BETWEEN 1 AND 73),
    alimento_kg        NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (alimento_kg >= 0),
    mortalidad         INTEGER NOT NULL DEFAULT 0 CHECK (mortalidad >= 0),    -- aves muertas del día
    novedad_sanitaria  TEXT,
    registrado_por     INTEGER NOT NULL REFERENCES usuarios(id),
    creado_en          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (lote_id, dia_ciclo)
);

-- =============================================================================
-- 7. DETALLE DE ASIENTOS (partida doble)
--    Cada línea es débito XOR crédito. Las líneas sobre un centro de costo
--    (6.1.01.01 / 6.1.01.02) llevan obligatoriamente centro + sufijo + lote.
-- =============================================================================

CREATE TABLE asiento_detalle (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    asiento_id       INTEGER NOT NULL REFERENCES asientos(id) ON DELETE CASCADE,
    linea            INTEGER NOT NULL CHECK (linea > 0),
    cuenta_id        INTEGER NOT NULL REFERENCES cuentas(id),
    glosa            TEXT,
    debe             NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (debe  >= 0),
    haber            NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (haber >= 0),
    moneda           TEXT NOT NULL DEFAULT 'BOB',
    monto_origen     NUMERIC(14,2),                       -- importe en moneda original (si no es BOB)
    tipo_cambio      NUMERIC(12,6) NOT NULL DEFAULT 1 CHECK (tipo_cambio > 0),
    centro_costo_id  INTEGER REFERENCES centros_costo(id),
    sufijo_id        INTEGER REFERENCES sufijos_costo(id),
    lote_id          INTEGER REFERENCES lotes(id),
    UNIQUE (asiento_id, linea),
    CHECK ((debe > 0 AND haber = 0) OR (haber > 0 AND debe = 0)),
    CHECK (sufijo_id IS NULL OR centro_costo_id IS NOT NULL),
    CHECK (lote_id   IS NULL OR centro_costo_id IS NOT NULL)
);
CREATE INDEX idx_detalle_cuenta ON asiento_detalle(cuenta_id);
CREATE INDEX idx_detalle_lote   ON asiento_detalle(lote_id);
CREATE INDEX idx_detalle_matriz ON asiento_detalle(centro_costo_id, sufijo_id);

