-- 9. VISTAS DE CONSULTA
--    Solo consideran asientos CONTABILIZADOS.
-- =============================================================================

-- Libro Diario
CREATE VIEW v_libro_diario AS
SELECT  a.ejercicio_id,
        a.id          AS asiento_id,
        a.numero,
        a.fecha,
        a.tipo,
        a.glosa       AS glosa_asiento,
        d.linea,
        c.codigo      AS cuenta_codigo,
        c.nombre      AS cuenta_nombre,
        d.glosa       AS glosa_linea,
        d.debe,
        d.haber,
        cc.codigo     AS centro_costo,
        s.codigo      AS sufijo,
        l.codigo      AS lote
FROM asientos a
JOIN asiento_detalle d      ON d.asiento_id = a.id
JOIN cuentas c              ON c.id = d.cuenta_id
LEFT JOIN centros_costo cc  ON cc.id = d.centro_costo_id
LEFT JOIN sufijos_costo s   ON s.id = d.sufijo_id
LEFT JOIN lotes l           ON l.id = d.lote_id
WHERE a.estado IN ('CONTABILIZADO', 'ANULADO');   -- los anulados se muestran junto a su contrapartida

-- Libro Mayor (saldo corrido por cuenta, en términos deudores)
CREATE VIEW v_libro_mayor AS
SELECT  a.ejercicio_id,
        c.id      AS cuenta_id,
        c.codigo  AS cuenta_codigo,
        c.nombre  AS cuenta_nombre,
        a.fecha,
        a.numero  AS asiento_numero,
        d.linea,
        d.debe,
        d.haber,
        SUM(d.debe - d.haber) OVER (
            PARTITION BY a.ejercicio_id, c.id
            ORDER BY a.fecha, a.numero, d.linea
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS saldo_deudor_corrido
FROM asiento_detalle d
JOIN asientos a ON a.id = d.asiento_id
JOIN cuentas  c ON c.id = d.cuenta_id
WHERE a.estado IN ('CONTABILIZADO', 'ANULADO');

-- Balance de Comprobación de Sumas y Saldos
CREATE VIEW v_balance_comprobacion AS
SELECT  a.ejercicio_id,
        c.codigo  AS cuenta_codigo,
        c.nombre  AS cuenta_nombre,
        c.naturaleza,
        ROUND(SUM(d.debe), 2)  AS suma_debe,
        ROUND(SUM(d.haber), 2) AS suma_haber,
        CASE WHEN SUM(d.debe) > SUM(d.haber) THEN ROUND(SUM(d.debe) - SUM(d.haber), 2) ELSE 0 END AS saldo_deudor,
        CASE WHEN SUM(d.haber) > SUM(d.debe) THEN ROUND(SUM(d.haber) - SUM(d.debe), 2) ELSE 0 END AS saldo_acreedor
FROM asiento_detalle d
JOIN asientos a ON a.id = d.asiento_id
JOIN cuentas  c ON c.id = d.cuenta_id
WHERE a.estado IN ('CONTABILIZADO', 'ANULADO')
GROUP BY a.ejercicio_id, c.id, c.codigo, c.nombre, c.naturaleza;

-- Hoja de costos: acumulación por lote x sufijo x elemento (insumo de FIN-TRA-06)
CREATE VIEW v_hoja_costos_lote AS
SELECT  l.id              AS lote_id,
        l.codigo          AS lote,
        cc.codigo         AS centro_costo,
        s.codigo          AS sufijo,
        s.nombre          AS sufijo_nombre,
        s.elemento_costo,
        ROUND(SUM(d.debe - d.haber), 2) AS monto
FROM asiento_detalle d
JOIN asientos a        ON a.id  = d.asiento_id
JOIN lotes l           ON l.id  = d.lote_id
JOIN centros_costo cc  ON cc.id = d.centro_costo_id
JOIN sufijos_costo s   ON s.id  = d.sufijo_id
WHERE a.estado IN ('CONTABILIZADO', 'ANULADO')
GROUP BY l.id, l.codigo, cc.codigo, s.codigo, s.nombre, s.elemento_costo;

-- Mortalidad acumulada vs. umbral de pérdida normal (5 %, MAN-01 8.3)
CREATE VIEW v_lote_mortalidad AS
SELECT  l.id          AS lote_id,
        l.codigo      AS lote,
        l.aves_iniciales,
        COALESCE(SUM(b.mortalidad), 0) AS mortalidad_acumulada,
        CASE WHEN l.aves_iniciales > 0
             THEN ROUND(100.0 * COALESCE(SUM(b.mortalidad), 0) / l.aves_iniciales, 2) END AS pct_mortalidad,
        CASE WHEN l.aves_iniciales > 0
              AND 100.0 * COALESCE(SUM(b.mortalidad), 0) / l.aves_iniciales > 5
             THEN 'ANORMAL' ELSE 'NORMAL' END AS clasificacion,
        CASE WHEN l.aves_iniciales > 0
              AND COALESCE(SUM(b.mortalidad), 0) > l.aves_iniciales * 0.05
             THEN COALESCE(SUM(b.mortalidad), 0) - l.aves_iniciales * 0.05 ELSE 0 END AS aves_exceso_sobre_5pct
FROM lotes l
LEFT JOIN lote_bitacora b ON b.lote_id = l.id
GROUP BY l.id, l.codigo, l.aves_iniciales;

-- =============================================================================
-- 10. TRIGGERS (SQLite) — reglas que un CHECK no puede expresar
-- =============================================================================

-- 10.1 Plan de cuentas: el padre debe ser del nivel inmediato superior y su
--      código debe ser prefijo del código hijo (1.1.03 -> 1.1.03.12).
CREATE TRIGGER trg_cuentas_jerarquia
BEFORE INSERT ON cuentas
WHEN NEW.cuenta_padre_id IS NOT NULL
BEGIN
    SELECT RAISE(ABORT, 'Jerarquía inválida: el padre debe ser del nivel inmediato superior y su código prefijo del hijo')
    WHERE NOT EXISTS (
        SELECT 1 FROM cuentas p
        WHERE p.id = NEW.cuenta_padre_id
          AND p.nivel = NEW.nivel - 1
          AND substr(NEW.codigo, 1, length(p.codigo) + 1) = p.codigo || '.'
    );
END;

-- 10.2 Un centro de costo solo puede apuntar a una cuenta marcada como centro de costo.
CREATE TRIGGER trg_centros_costo_cuenta
BEFORE INSERT ON centros_costo
BEGIN
    SELECT RAISE(ABORT, 'La cuenta del centro de costo debe tener es_centro_costo = 1')
    WHERE NOT EXISTS (SELECT 1 FROM cuentas WHERE id = NEW.cuenta_id AND es_centro_costo = 1);
END;

-- 10.3 Asientos: solo en ejercicio ABIERTO y con fecha dentro del ejercicio.
CREATE TRIGGER trg_asientos_ejercicio
BEFORE INSERT ON asientos
BEGIN
    SELECT RAISE(ABORT, 'El ejercicio fiscal no está ABIERTO')
    WHERE NOT EXISTS (SELECT 1 FROM ejercicios_fiscales WHERE id = NEW.ejercicio_id AND estado = 'ABIERTO');
    SELECT RAISE(ABORT, 'La fecha del asiento está fuera del ejercicio fiscal')
    WHERE NOT EXISTS (
        SELECT 1 FROM ejercicios_fiscales
        WHERE id = NEW.ejercicio_id AND NEW.fecha BETWEEN fecha_inicio AND fecha_fin
    );
END;

-- 10.4 Contabilizar: mínimo 2 líneas y asiento cuadrado (debe = haber).
CREATE TRIGGER trg_asientos_cuadre
BEFORE UPDATE OF estado ON asientos
WHEN OLD.estado = 'BORRADOR' AND NEW.estado = 'CONTABILIZADO'
BEGIN
    SELECT RAISE(ABORT, 'El asiento necesita al menos dos líneas')
    WHERE (SELECT COUNT(*) FROM asiento_detalle WHERE asiento_id = NEW.id) < 2;
    SELECT RAISE(ABORT, 'Asiento descuadrado: la suma del debe no es igual a la del haber')
    WHERE (SELECT ROUND(COALESCE(SUM(debe), 0), 2)  FROM asiento_detalle WHERE asiento_id = NEW.id)
       <> (SELECT ROUND(COALESCE(SUM(haber), 0), 2) FROM asiento_detalle WHERE asiento_id = NEW.id);
END;

-- 10.5 Inmutabilidad: un asiento no-BORRADOR solo puede pasar de CONTABILIZADO a ANULADO.
CREATE TRIGGER trg_asientos_inmutable
BEFORE UPDATE ON asientos
WHEN OLD.estado <> 'BORRADOR'
BEGIN
    SELECT RAISE(ABORT, 'Asiento contabilizado/anulado: no se puede modificar (use un asiento de ANULACION)')
    WHERE NOT (
        OLD.estado = 'CONTABILIZADO' AND NEW.estado = 'ANULADO'
        AND NEW.ejercicio_id = OLD.ejercicio_id AND NEW.numero = OLD.numero
        AND NEW.fecha = OLD.fecha AND NEW.tipo = OLD.tipo AND NEW.glosa = OLD.glosa
        AND NEW.creado_por = OLD.creado_por
        AND COALESCE(NEW.autorizado_por, 0) = COALESCE(OLD.autorizado_por, 0)
    );
END;

CREATE TRIGGER trg_asientos_no_borrar
BEFORE DELETE ON asientos
WHEN OLD.estado <> 'BORRADOR'
BEGIN
    SELECT RAISE(ABORT, 'No se puede eliminar un asiento contabilizado o anulado');
END;

-- 10.6 Detalle: validaciones de cuenta, matriz de costos y lote.
CREATE TRIGGER trg_detalle_validar
BEFORE INSERT ON asiento_detalle
BEGIN
    SELECT RAISE(ABORT, 'Solo se pueden agregar líneas a un asiento en BORRADOR')
    WHERE NOT EXISTS (SELECT 1 FROM asientos WHERE id = NEW.asiento_id AND estado = 'BORRADOR');

    SELECT RAISE(ABORT, 'La cuenta debe ser imputable (nivel 4) y estar activa')
    WHERE NOT EXISTS (SELECT 1 FROM cuentas WHERE id = NEW.cuenta_id AND es_imputable = 1 AND activa = 1);

    -- Cuenta-centro de costo (6.1.01.01 / 6.1.01.02): exige centro + sufijo + lote
    SELECT RAISE(ABORT, 'Las líneas en un centro de costo requieren centro, sufijo y lote')
    WHERE EXISTS (SELECT 1 FROM cuentas WHERE id = NEW.cuenta_id AND es_centro_costo = 1)
      AND (NEW.centro_costo_id IS NULL OR NEW.sufijo_id IS NULL OR NEW.lote_id IS NULL);

    -- Un sufijo solo se usa sobre la cuenta del centro de costo indicado
    SELECT RAISE(ABORT, 'El sufijo solo aplica a la cuenta del centro de costo indicado')
    WHERE NEW.sufijo_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM centros_costo WHERE id = NEW.centro_costo_id AND cuenta_id = NEW.cuenta_id AND activo = 1);

    -- Matriz centro x sufijo y vigencia del sufijo
    SELECT RAISE(ABORT, 'Sufijo no permitido para ese centro de costo (matriz centro x sufijo) o inactivo')
    WHERE NEW.sufijo_id IS NOT NULL
      AND NOT EXISTS (
          SELECT 1 FROM centro_costo_sufijos m
          JOIN sufijos_costo s ON s.id = m.sufijo_id
          WHERE m.centro_costo_id = NEW.centro_costo_id AND m.sufijo_id = NEW.sufijo_id AND s.activo = 1
      );

    -- El lote debe pertenecer al centro; para acumular costos debe estar ABIERTO
    SELECT RAISE(ABORT, 'El lote no pertenece al centro de costo indicado')
    WHERE NEW.lote_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM lotes WHERE id = NEW.lote_id AND centro_costo_id = NEW.centro_costo_id);

    SELECT RAISE(ABORT, 'No se pueden acumular costos en un lote que no está ABIERTO')
    WHERE NEW.sufijo_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM lotes WHERE id = NEW.lote_id AND estado = 'ABIERTO');
END;

CREATE TRIGGER trg_detalle_no_modificar
BEFORE UPDATE ON asiento_detalle
BEGIN
    SELECT RAISE(ABORT, 'Solo se pueden modificar líneas de un asiento en BORRADOR')
    WHERE NOT EXISTS (SELECT 1 FROM asientos WHERE id = OLD.asiento_id AND estado = 'BORRADOR');

    SELECT RAISE(ABORT, 'Cuenta, centro, sufijo, lote y asiento de una línea son inmutables (elimine y vuelva a crear la línea)')
    WHERE NEW.asiento_id <> OLD.asiento_id
       OR NEW.cuenta_id  <> OLD.cuenta_id
       OR COALESCE(NEW.centro_costo_id, 0) <> COALESCE(OLD.centro_costo_id, 0)
       OR COALESCE(NEW.sufijo_id, 0)       <> COALESCE(OLD.sufijo_id, 0)
       OR COALESCE(NEW.lote_id, 0)         <> COALESCE(OLD.lote_id, 0);
END;

CREATE TRIGGER trg_detalle_no_borrar
BEFORE DELETE ON asiento_detalle
BEGIN
    SELECT RAISE(ABORT, 'Solo se pueden eliminar líneas de un asiento en BORRADOR')
    WHERE NOT EXISTS (SELECT 1 FROM asientos WHERE id = OLD.asiento_id AND estado = 'BORRADOR');
END;

-- 10.7 Lotes: el centro debe estar activo; el cierre exige un asiento CIERRE_CICLO contabilizado.
CREATE TRIGGER trg_lotes_alta
BEFORE INSERT ON lotes
BEGIN
    SELECT RAISE(ABORT, 'El centro de costo no está activo')
    WHERE NOT EXISTS (SELECT 1 FROM centros_costo WHERE id = NEW.centro_costo_id AND activo = 1);
END;

CREATE TRIGGER trg_lotes_cierre
BEFORE UPDATE OF estado ON lotes
WHEN OLD.estado = 'ABIERTO' AND NEW.estado = 'CERRADO'
BEGIN
    SELECT RAISE(ABORT, 'El cierre del lote exige un asiento CIERRE_CICLO contabilizado y autorizado')
    WHERE NOT EXISTS (
        SELECT 1 FROM asientos
        WHERE id = NEW.asiento_cierre_id AND tipo = 'CIERRE_CICLO'
          AND estado = 'CONTABILIZADO' AND autorizado_por IS NOT NULL
    );
END;

CREATE TRIGGER trg_lotes_cerrado_inmutable
BEFORE UPDATE ON lotes
WHEN OLD.estado = 'CERRADO'
BEGIN
    SELECT RAISE(ABORT, 'Un lote CERRADO no se puede modificar');
END;

-- 10.8 Bitácora: lote ABIERTO, fecha dentro del ciclo y día coherente con la fecha.
CREATE TRIGGER trg_bitacora_validar
BEFORE INSERT ON lote_bitacora
BEGIN
    SELECT RAISE(ABORT, 'La bitácora solo admite registros en lotes ABIERTOS')
    WHERE NOT EXISTS (SELECT 1 FROM lotes WHERE id = NEW.lote_id AND estado = 'ABIERTO');

    SELECT RAISE(ABORT, 'dia_ciclo no coincide con la fecha (día 1 = fecha de inicio del lote)')
    WHERE NOT EXISTS (
        SELECT 1 FROM lotes
        WHERE id = NEW.lote_id
          AND CAST(julianday(NEW.fecha) - julianday(fecha_inicio) AS INTEGER) + 1 = NEW.dia_ciclo
    );
END;
